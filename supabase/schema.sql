-- 1. Core Academic Structure
CREATE TABLE IF NOT EXISTS public.departments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL UNIQUE,
  head_name TEXT,
  description TEXT,
  established_year INTEGER,
  building_location TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.programs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  department_id BIGINT NOT NULL REFERENCES public.departments(id) ON DELETE CASCADE,
  degree_level TEXT NOT NULL,
  duration_years INTEGER NOT NULL DEFAULT 4,
  total_semesters INTEGER NOT NULL DEFAULT 8,
  credit_hours INTEGER NOT NULL DEFAULT 130,
  status TEXT NOT NULL DEFAULT 'Active',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.semesters (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  academic_year TEXT NOT NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  is_current BOOLEAN NOT NULL DEFAULT FALSE
);

-- 2. Faculty & Courses
CREATE TABLE IF NOT EXISTS public.faculty (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  email TEXT NOT NULL UNIQUE,
  phone TEXT,
  photo_url TEXT,
  department_id BIGINT NOT NULL REFERENCES public.departments(id) ON DELETE RESTRICT,
  designation TEXT NOT NULL,
  qualification TEXT NOT NULL,
  specialization TEXT,
  subjects_taught TEXT,
  experience_years INTEGER NOT NULL DEFAULT 0 CHECK (experience_years >= 0),
  joining_date DATE NOT NULL,
  responsibilities TEXT,
  status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'On Leave', 'Retired')),
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.courses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  title TEXT NOT NULL,
  department_id BIGINT NOT NULL REFERENCES public.departments(id) ON DELETE CASCADE,
  program_id BIGINT REFERENCES public.programs(id) ON DELETE SET NULL,
  semester_number INTEGER NOT NULL DEFAULT 1,
  credit_hours INTEGER NOT NULL DEFAULT 3,
  instructor_id BIGINT REFERENCES public.faculty(id) ON DELETE SET NULL,
  schedule_slot TEXT,
  room_number TEXT
);

-- 3. Centralized Student Registry
CREATE TABLE IF NOT EXISTS public.students (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_uid TEXT NOT NULL UNIQUE,
  registration_number TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  email TEXT,
  phone TEXT,
  photo_url TEXT,
  department_id BIGINT NOT NULL REFERENCES public.departments(id) ON DELETE RESTRICT,
  program_id BIGINT REFERENCES public.programs(id) ON DELETE SET NULL,
  current_semester INTEGER NOT NULL DEFAULT 1 CHECK (current_semester BETWEEN 1 AND 12),
  admission_year INTEGER NOT NULL CHECK (admission_year BETWEEN 2015 AND 2040),
  batch_label TEXT NOT NULL,
  cgpa NUMERIC(3, 2) CHECK (cgpa IS NULL OR (cgpa >= 0 AND cgpa <= 4.00)),
  academic_status TEXT NOT NULL DEFAULT 'Active' CHECK (academic_status IN ('Active', 'Probation', 'Graduated', 'On Leave')),
  guardian_name TEXT NOT NULL,
  guardian_phone TEXT,
  guardian_relation TEXT DEFAULT 'Father',
  address TEXT,
  cnic TEXT,
  date_of_birth DATE,
  is_demo BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Users & RBAC Linkages (linked to Supabase auth.users.id)
CREATE TABLE IF NOT EXISTS public.users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  auth_uid UUID UNIQUE REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER', 'STUDENT')),
  department_id BIGINT REFERENCES public.departments(id) ON DELETE SET NULL,
  linked_student_id BIGINT REFERENCES public.students(id) ON DELETE SET NULL,
  linked_faculty_id BIGINT REFERENCES public.faculty(id) ON DELETE SET NULL,
  avatar_url TEXT,
  status TEXT NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Suspended')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Attendance, Exams & Academic Results
CREATE TABLE IF NOT EXISTS public.attendance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  department_id BIGINT NOT NULL REFERENCES public.departments(id) ON DELETE CASCADE,
  semester_id BIGINT REFERENCES public.semesters(id) ON DELETE SET NULL,
  attendance_date DATE NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Present', 'Absent', 'Leave', 'Late')),
  marked_by_user_id BIGINT REFERENCES public.users(id) ON DELETE SET NULL,
  remarks TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, course_id, attendance_date)
);

CREATE TABLE IF NOT EXISTS public.examinations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title TEXT NOT NULL,
  exam_type TEXT NOT NULL,
  semester_id BIGINT REFERENCES public.semesters(id) ON DELETE SET NULL,
  department_id BIGINT REFERENCES public.departments(id) ON DELETE SET NULL,
  exam_date DATE NOT NULL,
  total_marks NUMERIC(6, 2) NOT NULL DEFAULT 100,
  status TEXT NOT NULL DEFAULT 'Completed'
);

CREATE TABLE IF NOT EXISTS public.results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  course_id BIGINT NOT NULL REFERENCES public.courses(id) ON DELETE CASCADE,
  semester_id BIGINT NOT NULL REFERENCES public.semesters(id) ON DELETE CASCADE,
  examination_id BIGINT REFERENCES public.examinations(id) ON DELETE SET NULL,
  marks_obtained NUMERIC(6, 2) NOT NULL,
  total_marks NUMERIC(6, 2) NOT NULL DEFAULT 100,
  grade TEXT NOT NULL,
  gpa_points NUMERIC(3, 2) NOT NULL,
  status TEXT NOT NULL DEFAULT 'Passed',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  UNIQUE (student_id, course_id, semester_id)
);

