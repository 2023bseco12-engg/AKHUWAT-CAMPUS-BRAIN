CREATE OR REPLACE FUNCTION public.current_app_role()
RETURNS TEXT
LANGUAGE SQL
STABLE
SECURITY DEFINER
AS $$
  SELECT role FROM public.users WHERE auth_uid = auth.uid() AND status = 'Active' LIMIT 1;
$$;

CREATE OR REPLACE FUNCTION public.current_linked_student_id()
RETURNS BIGINT
LANGUAGE SQL
STABLE
SECURITY DEFINER
AS $$
  SELECT linked_student_id FROM public.users WHERE auth_uid = auth.uid() AND status = 'Active' LIMIT 1;
$$;

