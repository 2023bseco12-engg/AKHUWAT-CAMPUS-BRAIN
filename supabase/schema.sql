-- Reference Tables: Authenticated Read, Admin Write
CREATE POLICY "Authenticated read departments" ON public.departments FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin manage departments" ON public.departments FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));

CREATE POLICY "Authenticated read programs" ON public.programs FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin manage programs" ON public.programs FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));

CREATE POLICY "Authenticated read courses" ON public.courses FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin manage courses" ON public.courses FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));

-- Students: Admin/Teacher read all, Student reads own row only; Admin writes
CREATE POLICY "Staff read students or student reads own" ON public.students FOR SELECT TO authenticated
  USING (
    public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER')
    OR id = public.current_linked_student_id()
  );
CREATE POLICY "Admin insert update delete students" ON public.students FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));

-- Faculty: Authenticated read, Admin writes
CREATE POLICY "Authenticated read faculty" ON public.faculty FOR SELECT TO authenticated USING (true);
CREATE POLICY "Admin manage faculty" ON public.faculty FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));

-- Attendance & Results: Staff read/write, Student reads own rows only
CREATE POLICY "Staff read attendance or student own" ON public.attendance FOR SELECT TO authenticated
  USING (
    public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER')
    OR student_id = public.current_linked_student_id()
  );
CREATE POLICY "Staff mark attendance" ON public.attendance FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER'));

CREATE POLICY "Staff read results or student own" ON public.results FOR SELECT TO authenticated
  USING (
    public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER')
    OR student_id = public.current_linked_student_id()
  );
CREATE POLICY "Staff record results" ON public.results FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN', 'TEACHER'));

-- Confidential Financial Assistance: Strictly Admins & Own Student only (Teachers blocked)
CREATE POLICY "Admin or own student read financial assistance" ON public.financial_assistance FOR SELECT TO authenticated
  USING (
    public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN')
    OR student_id = public.current_linked_student_id()
  );
CREATE POLICY "Admin manage financial assistance" ON public.financial_assistance FOR ALL TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'))
  WITH CHECK (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));

-- Users & Audit Logs: Self profile read, Super Admin/Admin governance
CREATE POLICY "User read own profile or admin read all" ON public.users FOR SELECT TO authenticated
  USING (auth_uid = auth.uid() OR public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));
CREATE POLICY "Super Admin manage users" ON public.users FOR ALL TO authenticated
  USING (public.current_app_role() = 'SUPER_ADMIN')
  WITH CHECK (public.current_app_role() = 'SUPER_ADMIN');

CREATE POLICY "Admins read audit logs" ON public.audit_logs FOR SELECT TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));
CREATE POLICY "Admins read import history" ON public.import_history FOR SELECT TO authenticated
  USING (public.current_app_role() IN ('SUPER_ADMIN', 'ADMIN'));
